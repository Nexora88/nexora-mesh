//! Store-and-forward routing primitives for the transport-independent mesh core.
//!
//! This module routes opaque ciphertext only. It does not implement cryptography,
//! identity lookup, radio transport, or a complete wire codec. Callers MUST encrypt
//! and authenticate payloads end-to-end before placing them in an Envelope.
use std::collections::{HashSet, VecDeque};

pub const MAX_CIPHERTEXT_BYTES: usize = 256 * 1024;
pub const MAX_HOPS: u8 = 5;
pub const MAX_QUEUE_ITEMS: usize = 128;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Envelope {
    /// Random 128-bit identifier generated by the sender; not a user identity.
    pub message_id: [u8; 16],
    /// Opaque destination routing token. This is metadata and may reveal correlation.
    pub destination_token: [u8; 16],
    /// Remaining relay budget. Decremented once per forwarding hop.
    pub hops_remaining: u8,
    /// Unix timestamp after which relays must discard the envelope.
    pub expires_at_unix: u64,
    /// Must contain authenticated end-to-end ciphertext, never plaintext.
    pub ciphertext: Vec<u8>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RelayDecision {
    Forward,
    DeliverLocally,
    DropDuplicate,
    DropExpired,
    DropHopLimit,
    DropOversized,
    DropRelayDisabled,
}

impl Envelope {
    pub fn validate(&self, now_unix: u64) -> RelayDecision {
        if self.ciphertext.is_empty() || self.ciphertext.len() > MAX_CIPHERTEXT_BYTES {
            return RelayDecision::DropOversized;
        }
        if self.expires_at_unix <= now_unix {
            return RelayDecision::DropExpired;
        }
        if self.hops_remaining == 0 || self.hops_remaining > MAX_HOPS {
            return RelayDecision::DropHopLimit;
        }
        RelayDecision::Forward
    }

    /// Make a relay copy with one fewer hop. Returns None when no forwarding is allowed.
    pub fn forwarded(&self, now_unix: u64) -> Option<Self> {
        if self.validate(now_unix) != RelayDecision::Forward {
            return None;
        }
        let mut next = self.clone();
        next.hops_remaining -= 1;
        Some(next)
    }
}

/// Coarse power/activity state supplied by the native host; no background work is
/// performed by this policy itself. Native Android/iOS schedulers must honor OS limits.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RelayPowerState {
    pub battery_percent: u8,
    pub charging: bool,
    pub low_power_mode: bool,
    pub app_foreground: bool,
    pub recently_connected: bool,
    pub urgent_pending: bool,
}

/// Battery-aware scan cadence. Values are recommendations, not a promise that the OS
/// will schedule BLE work at these intervals.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SmartRelayPolicy {
    pub minimum_battery_percent: u8,
    pub foreground_scan_seconds: u64,
    pub idle_scan_seconds: u64,
    pub deep_sleep_seconds: u64,
}

impl Default for SmartRelayPolicy {
    fn default() -> Self {
        Self {
            minimum_battery_percent: 15,
            foreground_scan_seconds: 5,
            idle_scan_seconds: 45,
            deep_sleep_seconds: 300,
        }
    }
}

impl SmartRelayPolicy {
    pub fn may_scan(&self, state: RelayPowerState) -> bool {
        state.app_foreground
            || state.charging
            || (state.battery_percent >= self.minimum_battery_percent && !state.low_power_mode)
    }

    pub fn may_relay(&self, state: RelayPowerState, opted_in: bool) -> bool {
        opted_in
            && self.may_scan(state)
            && (state.app_foreground
                || state.charging
                || state.battery_percent >= self.minimum_battery_percent)
    }

    pub fn recommended_scan_interval_seconds(&self, state: RelayPowerState) -> u64 {
        if !self.may_scan(state) {
            return self.deep_sleep_seconds;
        }
        if state.app_foreground || state.charging || state.recently_connected || state.urgent_pending {
            self.foreground_scan_seconds
        } else {
            self.idle_scan_seconds
        }
    }
}

/// Small bounded in-memory queue and duplicate cache for a relay node.
/// Persistence and background service integration are intentionally left to the app layer.
#[derive(Debug)]
pub struct RelayQueue {
    capacity: usize,
    queue: VecDeque<Envelope>,
    seen: HashSet<[u8; 16]>,
    seen_order: VecDeque<[u8; 16]>,
    seen_capacity: usize,
    relay_enabled: bool,
}

impl Default for RelayQueue {
    fn default() -> Self {
        Self::new(MAX_QUEUE_ITEMS, MAX_QUEUE_ITEMS * 4)
    }
}

impl RelayQueue {
    pub fn new(capacity: usize, seen_capacity: usize) -> Self {
        Self {
            capacity: capacity.max(1),
            queue: VecDeque::new(),
            seen: HashSet::new(),
            seen_order: VecDeque::new(),
            seen_capacity: seen_capacity.max(1),
            // Forwarding is privacy-sensitive and must be explicitly opted into.
            relay_enabled: false,
        }
    }

    pub fn set_relay_enabled(&mut self, enabled: bool) {
        self.relay_enabled = enabled;
        if !enabled {
            self.queue.clear();
        }
    }

    pub fn relay_enabled(&self) -> bool {
        self.relay_enabled
    }

    pub fn len(&self) -> usize {
        self.queue.len()
    }

    pub fn is_empty(&self) -> bool {
        self.queue.is_empty()
    }

    /// Accept only a fresh, valid envelope. The caller must supply trusted local time.
    pub fn enqueue(&mut self, envelope: Envelope, now_unix: u64) -> RelayDecision {
        if !self.relay_enabled {
            return RelayDecision::DropRelayDisabled;
        }
        let validation = envelope.validate(now_unix);
        if validation != RelayDecision::Forward {
            return validation;
        }
        if self.seen.contains(&envelope.message_id) {
            return RelayDecision::DropDuplicate;
        }
        if self.queue.len() >= self.capacity {
            return RelayDecision::DropOversized;
        }
        self.remember(envelope.message_id);
        self.queue.push_back(envelope);
        RelayDecision::Forward
    }

    /// Return a bounded snapshot suitable for durable app-layer storage.
    /// The snapshot contains opaque ciphertext envelopes only; it does not include keys.
    pub fn persisted_snapshot(&self) -> Result<Vec<Vec<u8>>, crate::wire::WireError> {
        self.queue.iter().map(crate::wire::encode_envelope).collect()
    }

    /// Restore valid, unexpired envelopes from durable app storage.
    /// Call only after the user opts in to relaying. Invalid records are skipped.
    pub fn restore_persisted(&mut self, records: &[Vec<u8>], now_unix: u64) -> usize {
        if !self.relay_enabled {
            return 0;
        }
        let mut restored = 0;
        for record in records {
            if self.queue.len() >= self.capacity {
                break;
            }
            let Ok(envelope) = crate::wire::decode_envelope(record) else { continue };
            if envelope.validate(now_unix) != RelayDecision::Forward
                || self.seen.contains(&envelope.message_id)
            {
                continue;
            }
            self.remember(envelope.message_id);
            self.queue.push_back(envelope);
            restored += 1;
        }
        restored
    }

    pub fn pop_next(&mut self, now_unix: u64) -> Option<Envelope> {
        while let Some(envelope) = self.queue.pop_front() {
            if envelope.expires_at_unix > now_unix && envelope.hops_remaining > 0 {
                return Some(envelope);
            }
        }
        None
    }

    fn remember(&mut self, id: [u8; 16]) {
        if self.seen.insert(id) {
            self.seen_order.push_back(id);
            while self.seen_order.len() > self.seen_capacity {
                if let Some(oldest) = self.seen_order.pop_front() {
                    self.seen.remove(&oldest);
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn envelope(id: u8, hops: u8, expires: u64) -> Envelope {
        Envelope {
            message_id: [id; 16],
            destination_token: [9; 16],
            hops_remaining: hops,
            expires_at_unix: expires,
            ciphertext: b"opaque-ciphertext".to_vec(),
        }
    }

    #[test]
    fn relay_is_disabled_by_default_and_can_be_opted_in() {
        let mut queue = RelayQueue::new(4, 8);
        assert!(!queue.relay_enabled());
        assert_eq!(
            queue.enqueue(envelope(1, 3, 100), 1),
            RelayDecision::DropRelayDisabled
        );
        queue.set_relay_enabled(true);
        assert!(queue.relay_enabled());
        assert_eq!(
            queue.enqueue(envelope(1, 3, 100), 1),
            RelayDecision::Forward
        );
        queue.set_relay_enabled(false);
        assert!(queue.is_empty());
    }

    #[test]
    fn forwarding_decrements_hops_without_changing_ciphertext() {
        let original = envelope(1, 3, 100);
        let forwarded = original.forwarded(10).unwrap();
        assert_eq!(forwarded.hops_remaining, 2);
        assert_eq!(forwarded.ciphertext, original.ciphertext);
        assert_eq!(original.hops_remaining, 3);
    }

    #[test]
    fn expired_and_zero_hop_messages_are_rejected() {
        assert_eq!(envelope(1, 2, 10).validate(10), RelayDecision::DropExpired);
        assert_eq!(
            envelope(2, 0, 100).validate(10),
            RelayDecision::DropHopLimit
        );
    }

    #[test]
    fn duplicate_message_ids_are_not_queued_twice() {
        let mut queue = RelayQueue::new(4, 8);
        queue.set_relay_enabled(true);
        assert_eq!(
            queue.enqueue(envelope(1, 3, 100), 1),
            RelayDecision::Forward
        );
        assert_eq!(
            queue.enqueue(envelope(1, 3, 100), 1),
            RelayDecision::DropDuplicate
        );
        assert_eq!(queue.len(), 1);
    }

    #[test]
    fn queue_capacity_is_bounded() {
        let mut queue = RelayQueue::new(1, 8);
        queue.set_relay_enabled(true);
        assert_eq!(
            queue.enqueue(envelope(1, 3, 100), 1),
            RelayDecision::Forward
        );
        assert_eq!(
            queue.enqueue(envelope(2, 3, 100), 1),
            RelayDecision::DropOversized
        );
    }

    #[test]
    fn expired_items_are_discarded_when_popped() {
        let mut queue = RelayQueue::new(4, 8);
        queue.set_relay_enabled(true);
        queue.enqueue(envelope(1, 3, 5), 1);
        queue.enqueue(envelope(2, 3, 50), 1);
        assert_eq!(queue.pop_next(10).unwrap().message_id, [2; 16]);
        assert!(queue.is_empty());
    }

    #[test]
    fn smart_relay_policy_sleeps_on_low_battery_and_respects_opt_in() {
        let policy = SmartRelayPolicy::default();
        let low = RelayPowerState {
            battery_percent: 8,
            charging: false,
            low_power_mode: true,
            app_foreground: false,
            recently_connected: false,
            urgent_pending: false,
        };
        assert!(!policy.may_scan(low));
        assert!(!policy.may_relay(low, true));
        assert_eq!(policy.recommended_scan_interval_seconds(low), 300);
        assert!(!policy.may_relay(RelayPowerState { app_foreground: true, ..low }, false));
    }

    #[test]
    fn persisted_queue_restores_only_valid_envelopes_after_opt_in() {
        let mut source = RelayQueue::new(4, 8);
        source.set_relay_enabled(true);
        source.enqueue(envelope(9, 3, 100), 1);
        let records = source.persisted_snapshot().unwrap();

        let mut target = RelayQueue::new(4, 8);
        assert_eq!(target.restore_persisted(&records, 2), 0);
        target.set_relay_enabled(true);
        assert_eq!(target.restore_persisted(&records, 2), 1);
        assert_eq!(target.pop_next(2).unwrap().message_id, [9; 16]);
    }

    #[test]
    fn three_node_store_and_forward_simulation_preserves_opaque_payload() {
        let sent = envelope(77, 3, 100);
        let mut relay_b = RelayQueue::new(4, 8);
        relay_b.set_relay_enabled(true);
        assert_eq!(relay_b.enqueue(sent.clone(), 10), RelayDecision::Forward);

        // B stores the opaque envelope, then spends exactly one hop when forwarding.
        let received_at_b = relay_b.pop_next(10).unwrap();
        let forwarded_by_b = received_at_b.forwarded(10).unwrap();
        assert_eq!(forwarded_by_b.hops_remaining, 2);
        assert_eq!(forwarded_by_b.ciphertext, sent.ciphertext);
        assert_eq!(forwarded_by_b.destination_token, sent.destination_token);

        let mut destination_c = RelayQueue::new(4, 8);
        destination_c.set_relay_enabled(true);
        assert_eq!(
            destination_c.enqueue(forwarded_by_b, 10),
            RelayDecision::Forward
        );
        let delivered_to_c = destination_c.pop_next(10).unwrap();
        assert_eq!(delivered_to_c.message_id, sent.message_id);
        assert_eq!(delivered_to_c.ciphertext, sent.ciphertext);
        assert_eq!(delivered_to_c.hops_remaining, 2);
    }
}
